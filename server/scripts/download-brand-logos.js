/**
 * Download a file from a URL
 */
function downloadFile(url, filePath) {
  return new Promise((resolve, reject) => {
    const protocol = url.startsWith('https') ? https : http;
    
    protocol.get(url, (response) => {
      // Handle redirects
      if (response.statusCode === 301 || response.statusCode === 302) {
        downloadFile(response.headers.location, filePath).then(resolve).catch(reject);
        return;
      }

      if (response.statusCode !== 200) {
        reject(new Error(`Failed to download: ${url} (status: ${response.statusCode})`));
        return;
      }

      const fileStream = fs.createWriteStream(filePath);
      response.pipe(fileStream);
      
      fileStream.on('finish', () => {
        fileStream.close();
        resolve();
      });
      
      fileStream.on('error', (err) => {
        fs.unlink(filePath, () => {}); // Delete the file if error occurs
        reject(err);
      });
    }).on('error', reject);
  });
}

/**
 * Download all brand logos
 */
async function downloadLogos() {
  console.log('Downloading brand logos from logo.dev...\n');
  
  let successful = 0;
  let failed = 0;
  const failedBrands = [];

  for (const [brandName, brandKey] of Object.entries(BRANDS)) {
    const url = `https://img.logo.dev/name/${encodeURIComponent(brandName)}?token=${LOGO_DEV_TOKEN}`;
    const fileName = `${brandKey}.png`;
    const filePath = path.join(outputDir, fileName);

    try {
      await downloadFile(url, filePath);
      console.log(`✓ Downloaded: ${brandName} → ${fileName}`);
      successful++;
    } catch (error) {
      console.error(`✗ Failed: ${brandName} - ${error.message}`);
      failed++;
      failedBrands.push(brandName);
    }
  }

  console.log(`\n✓ Download completed: ${successful} successful, ${failed} failed`);
  
  if (failedBrands.length > 0) {
    console.log(`\nFailed brands: ${failedBrands.join(', ')}`);
  }

  // Generate the mapping file
  console.log('\nGenerating brand logo mapping...');
  generateMappingFile();
}

